#!/bin/zsh
# uninstall.sh — remove the Quick Action, the ~/.zshrc line, state files and ~/.finder-follow.
emulate -L zsh
setopt no_unset

HERE=${${(%):-%x}:A:h}
BIN="$HERE/bin/finder-terminal"
SERVICES_DIR=${SERVICES_DIR:-$HOME/Library/Services}
ZSHRC=${ZSHRC:-$HOME/.zshrc}
MARK="# finder-terminal"
STATE_DIR=${FINDER_TERMINAL_STATE:-$HOME/.local/state/finder-terminal}
FOLLOW_FILE=${FINDER_FOLLOW_FILE:-$HOME/.finder-follow}

# close an open panel and stop the watcher
[[ -x $BIN ]] && "$BIN" close 2>/dev/null
if [[ -r $STATE_DIR/watcher.pid ]]; then kill "$(<$STATE_DIR/watcher.pid)" 2>/dev/null; fi

# Quick Action
if [[ -d "$SERVICES_DIR/Toggle Terminal Panel.workflow" ]]; then
  rm -rf "$SERVICES_DIR/Toggle Terminal Panel.workflow"
  /System/Library/CoreServices/pbs -flush 2>/dev/null
  /System/Library/CoreServices/pbs -update 2>/dev/null
  print "removed Quick Action"
fi

# ~/.zshrc line
if [[ -f $ZSHRC ]] && grep -qF "$MARK" "$ZSHRC"; then
  cp "$ZSHRC" "$ZSHRC.bak-finder-terminal"
  { grep -vF "$MARK" "$ZSHRC" || true; } > "$ZSHRC.tmp" && mv -f "$ZSHRC.tmp" "$ZSHRC"
  print "removed source line from $ZSHRC (backup: $ZSHRC.bak-finder-terminal)"
fi

# helper app (generated by install.sh)
rm -rf "$HERE/app/Finder Terminal.app" "$HERE/app/.built-for"

# state
rm -rf "$STATE_DIR"
rm -f "$FOLLOW_FILE" "$FOLLOW_FILE.tmp"
print "removed $STATE_DIR and $FOLLOW_FILE"
print "Not touched: this folder, macOS permission grants (System Settings > Privacy & Security), any Services keyboard shortcut you assigned."
